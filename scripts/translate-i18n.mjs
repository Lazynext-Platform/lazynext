function translateValue(value, dict) {
  if (typeof value !== 'string') return value;
  if (skipStrings.has(value)) return value;
  if (dict[value]) return dict[value];
  return value;
}

function deepTranslate(obj, dict) {
  const result = { ...obj };
  for (const [key, value] of Object.entries(result)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      result[key] = deepTranslate(value, dict);
    } else if (typeof value === 'string') {
      result[key] = translateValue(value, dict);
    }
  }
  return result;
}

function countTranslated(obj, dict) {
  let count = 0;
  for (const value of Object.values(obj)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      count += countTranslated(value, dict);
    } else if (typeof value === 'string' && dict[value] && !skipStrings.has(value)) {
      count++;
    }
  }
  return count;
}

