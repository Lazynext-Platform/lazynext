import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedDir = path.join(projectRoot, 'src', 'generated', 'platform');
const banner =
  `// AUTO-GENERATED by scripts/prepare-platform.mjs for cloudflare. Do not edit.\n`;

mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  path.join(generatedDir, 'prisma.ts'),
  `${banner}export { prisma } from '@/lib/prisma.cloudflare';\n`,
);
writeFileSync(
  path.join(generatedDir, 'media-storage.ts'),
  `${banner}export * from '@/lib/media-storage.cloudflare';\n`,
);

console.log('Prepared platform modules for cloudflare');
