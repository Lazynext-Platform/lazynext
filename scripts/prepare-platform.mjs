import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedDir = path.join(projectRoot, 'src', 'generated', 'platform');
const banner =
  `// AUTO-GENERATED by scripts/prepare-platform.mjs. Do not edit.\n`;

// When BUILD_TARGET is not 'cloudflare' (e.g. during `npm run dev` with
// Turbopack), use the local Node.js Prisma client so the dev server can
// authenticate and query the SQLite database without needing the Cloudflare
// workerd runtime / getCloudflareContext().
const target = process.env.BUILD_TARGET || 'cloudflare';
const isCloudflare = target === 'cloudflare';

mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  path.join(generatedDir, 'prisma.ts'),
  `${banner}export { prisma } from '@/lib/prisma.${isCloudflare ? 'cloudflare' : 'local'}';\n`,
);
writeFileSync(
  path.join(generatedDir, 'media-storage.ts'),
  `${banner}export * from '@/lib/media-storage.${isCloudflare ? 'cloudflare' : 'local'}';\n`,
);

console.log(`Prepared platform modules for ${target}`);
